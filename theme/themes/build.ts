// Writes one stylesheet per theme from themes.json, its scales under [data-palette="<id>"] and its
// dark re-points under .dark or data-theme="dark"; `--check` fails on any that differs instead.
import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import themes from './themes.json' with { type: 'json' };

type Role = 'primary' | 'secondary' | 'accent';
type Scale = Readonly<Record<string, string>>;

interface Theme {
  readonly id: string;
  readonly scales: Partial<Record<Role, Scale>>;
  readonly dark?: Partial<Record<Role, Scale>>;
}

const ROLES: readonly Role[] = ['primary', 'secondary', 'accent'];
const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const DARK = ":is(.dark, [data-theme='dark'])";
const HEADER = '/* Generated by themes/build.ts from themes.json; edit those, not this file. */\n';

const rule = (selector: string, declarations: readonly [string, string][]): string =>
  `${selector} {\n${declarations.map(([name, value]) => `  ${name}: ${value};\n`).join('')}}\n`;

const declarationsOf = (scales: Partial<Record<Role, Scale>>): [string, string][] =>
  ROLES.flatMap((role) =>
    Object.entries(scales[role] ?? {}).map(([step, value]): [string, string] => [
      `--color-${role}-${step}`,
      value,
    ]),
  );

const themeCss = ({ id, scales, dark = {} }: Theme): string => {
  const own = `[data-palette='${id}']`;
  const light = rule(own, declarationsOf(scales));
  const darkDeclarations = declarationsOf(dark);
  return darkDeclarations.length === 0
    ? light
    : `${light}\n${rule(`${DARK}${own},\n${DARK} ${own}`, darkDeclarations)}`;
};

/** The default theme re-aliased, for a swatch or region inside a themed page. */
const defaultCss = ({ id, aliases }: { id: string; aliases: Record<Role, string> }): string =>
  rule(
    `[data-palette='${id}']`,
    ROLES.flatMap((role) =>
      STEPS.map((step): [string, string] => [
        `--color-${role}-${step}`,
        `var(--color-${aliases[role]}-${step})`,
      ]),
    ),
  );

const files = [
  { id: themes.default.id, css: defaultCss(themes.default) },
  ...themes.themes.map((theme: Theme) => ({ id: theme.id, css: themeCss(theme) })),
];
const wanted = new Map(files.map(({ id, css }) => [`${id}.css`, HEADER + css]));
const listed = await readdir(import.meta.dirname);
const present = new Set(listed.filter((file) => file.endsWith('.css')));
const strays = [...present].filter((file) => !wanted.has(file));

if (process.argv.includes('--check')) {
  const changed = await Promise.all(
    [...wanted].map(async ([file, css]) =>
      present.has(file) && (await readFile(path.join(import.meta.dirname, file), 'utf8')) === css
        ? []
        : [file],
    ),
  );
  const stale = [...strays, ...changed.flat()];
  for (const file of stale) {
    console.error(`themes: ${file} differs from themes.json; run npm run build:themes.`);
  }
  process.exitCode = stale.length === 0 ? 0 : 1;
} else {
  await Promise.all([
    ...[...wanted].map(async ([file, css]) => writeFile(path.join(import.meta.dirname, file), css)),
    ...strays.map(async (file) => rm(path.join(import.meta.dirname, file))),
  ]);
  console.log(`themes: ${String(wanted.size)} stylesheets written`);
}
